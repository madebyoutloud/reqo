import type { Future } from '@outloud/future'
import { BaseClient } from './base_client.js'
import type {
  ClientOptions,
  OptionalResponseType as ResponseType,
  RequestOptions as BaseRequestOptions,
  ResponseOrData,
} from './types.js'
import type {
  HttpMethod,
  IsNever,
  MediaType,
  Operation,
  PathsWithMethod,
  RequestOptions as SchemaRequestOptions,
  RequiredKeys,
  ResponseObjectMap,
  SuccessResponse,
} from './schema.js'

declare const untyped: unique symbol

/**
 * Default `Paths` of a `Client`: methods accept any URL and options, `T` types the response data.
 * Keep it as the default of a subclass, `class ApiClient<P = Untyped> extends Client<P>`.
 */
export interface Untyped {
  readonly [untyped]: true
}

/** Adds behaviour to a client, e.g. hooks for auth or error normalization. */

export type Plugin = (client: Client<any>) => void

type IsAny<T> = 0 extends 1 & T ? true : false

/** Options of a request method of an untyped client */
type UntypedRequestOptions<
  D = any,
  Type extends ResponseType = ResponseType,
> = Omit<BaseRequestOptions<D, Type>, 'url' | 'method'>

/** Request method of an untyped client: any URL, `T` types the response data. */
export type UntypedMethod<ReturnData extends boolean = false> = <
  T,
  D = any,
  Type extends ResponseType = ResponseType,
>(url: string, options?: UntypedRequestOptions<D, Type>) => Future<ResponseOrData<T, Type, ReturnData>>

/** Request method of a typed client: paths, options and response data come from the schema. */
export type SchemaMethod<
  Paths,
  Method extends HttpMethod,
  ReturnData extends boolean = false,
  Media extends MediaType = MediaType,
> = <
  Path extends PathsWithMethod<Paths, Method>,
  Type extends ResponseType = ResponseType,
>(
  url: Path,
  ...options: IsNever<RequiredKeys<SchemaRequestOptions<Operation<Paths, Path, Method>, Type>>> extends true
    ? [options?: SchemaRequestOptions<Operation<Paths, Path, Method>, Type>]
    : [options: SchemaRequestOptions<Operation<Paths, Path, Method>, Type>]
) => Future<
  ResponseOrData<
    SuccessResponse<ResponseObjectMap<Operation<Paths, Path, Method>>, Media>,
    Type,
    ReturnData
  >
>

/** Request method of a client, untyped unless the client has `Paths`. */
export type ClientMethod<
  Paths,
  Method extends HttpMethod,
  ReturnData extends boolean = false,
> = IsAny<Paths> extends true
  ? UntypedMethod<ReturnData>
  : [Paths] extends [Untyped]
      ? UntypedMethod<ReturnData>
      : SchemaMethod<Paths, Method, ReturnData>

const shortcuts = ['get', 'head', 'post', 'patch', 'put', 'delete'] as const

/**
 * HTTP client. Without `Paths` it accepts any URL, with `Paths` (e.g. generated by openapi-typescript)
 * it types paths, options and response data from the schema.
 *
 * In a generic subclass the shortcut methods depend on the type parameter, call `this.request()` there.
 */
export class Client<Paths = Untyped> extends BaseClient {
  declare head: ClientMethod<Paths, 'head'>
  declare get: ClientMethod<Paths, 'get'>
  declare post: ClientMethod<Paths, 'post'>
  declare patch: ClientMethod<Paths, 'patch'>
  declare put: ClientMethod<Paths, 'put'>
  declare delete: ClientMethod<Paths, 'delete'>

  declare $get: ClientMethod<Paths, 'get', true>
  declare $post: ClientMethod<Paths, 'post', true>
  declare $patch: ClientMethod<Paths, 'patch', true>
  declare $put: ClientMethod<Paths, 'put', true>
  declare $delete: ClientMethod<Paths, 'delete', true>

  constructor(options: Partial<ClientOptions> = {}) {
    super(options)

    for (const plugin of options.plugins ?? []) {
      this.use(plugin)
    }
  }

  /** Applies a plugin to the client, returns the client. */
  use(plugin: Plugin): this {
    plugin(this)

    return this
  }
}

// defined once on the prototype, the declarations above type them for the client's `Paths`
function defineShortcut(name: string, method: string, returnData: boolean) {
  // a computed key names the function, so stack traces show e.g. `Client.get`
  const { [name]: value } = {
    [name](this: Client, url: string, options?: object) {
      const result = this.request({ ...options, url, method } as BaseRequestOptions)

      return returnData ? this.returnData(result) : result
    },
  }

  Object.defineProperty(Client.prototype, name, { configurable: true, writable: true, value })
}

for (const name of shortcuts) {
  defineShortcut(name, name.toUpperCase(), false)

  if (name !== 'head') {
    defineShortcut(`$${name}`, name.toUpperCase(), true)
  }
}
