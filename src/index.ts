/**
 * Creates a client, typed by `Paths` (e.g. generated by openapi-typescript) when given:
 * `createClient<paths>({ url })`.
 */
export function createClient<Paths = Untyped>(options: Partial<ClientOptions> = {}): Client<Paths> {
  return new Client<Paths>(options)
}

/** @deprecated Use `createClient<Paths>()`. */
export function createSchemaClient<Paths>(options?: Partial<ClientOptions>): Client<Paths> {
  return new Client<Paths>(options)
}

